// YouTube session material: cookies (and the visitor data they imply).
//
// WHY THIS EXISTS
//
// From a datacenter IP (Render, Railway, Fly, any VPS) YouTube answers
// "Sign in to confirm you're not a bot" for essentially every client, whether
// the request comes from yt-dlp, InnerTube or a frontend. It is not a bug we
// can code around: YouTube wants an account-backed session from IPs it doesn't
// trust. Cookies exported from a real browser session fix it, and that is what
// yt-dlp's own error message tells you to do.
//
// This module turns whatever form the cookies arrive in into the two shapes we
// need, so the rest of the pipeline doesn't care:
//
//   header()     "SID=...; HSID=..."   for InnerTube / youtubei.js
//   cookieFile() path to a Netscape cookies.txt  for yt-dlp --cookies
//
// Accepted sources, first match wins:
//
//   1. YT_COOKIES_B64        base64 of a cookies.txt or of a Cookie header.
//                            Best for hosts, because it is one line.
//   2. YT_COOKIES            a cookies.txt (Netscape) file's contents
//   3. YT_COOKIE             a Cookie header string ("a=b; c=d")
//   4. YT_COOKIES_FILE       path to a cookies.txt on disk
//   5. saved at runtime      `.play cookie <base64>` sent to the bot in a DM
//                            (stored via persist -> MongoDB when configured,
//                            so it survives redeploys)
//
// Nothing here ever logs a cookie value.

const fs = require("fs");
const path = require("path");

const persist = require("../persist");
const { BASE_DIR, DATA_DIR } = require("../dataDir");

const STORE = "ytCookies";
const STATUS_FILE = path.join(BASE_DIR, "media", "yt-cookies.txt");
const FALLBACK_FILE = path.join(DATA_DIR, "yt-cookies.txt");

// Cookies that only exist on a signed-in session. If none of these are
// present the export is useless for bot checks (a visitor-only export is the
// usual mistake).
// A browser export contains EVERY site's cookies — Railway dashboards, Stripe,
// hCaptcha, whatever else was open. The bot needs YouTube and nothing else, so
// anything outside these domains is dropped on the way in: it never reaches
// MongoDB, the cookie file, or a request header.
const RELEVANT_DOMAIN =
  /(^|\.)(youtube\.com|youtube-nocookie\.com|googlevideo\.com|google\.com|google\.com\.[a-z]{2}|google\.co\.[a-z]{2}|accounts\.google\.com|ogs\.google\.com)$/i;

const AUTH_COOKIES = [
  "SID",
  "HSID",
  "SSID",
  "APISID",
  "SAPISID",
  "__Secure-1PSID",
  "__Secure-3PSID",
  "__Secure-1PAPISID",
  "__Secure-3PAPISID",
  "LOGIN_INFO",
];

// Names that only appear in a real YouTube/Google cookie export. Anything else
// ("a=b", pasted JSON, a random word) is rejected rather than written out as a
// cookie file that silently does nothing.
const KNOWN_COOKIE = /^(SID|HSID|SSID|APISID|SAPISID|SIDCC|LOGIN_INFO|VISITOR_INFO1_LIVE|VISITOR_DATA|PREF|YSC|CONSENT|STAMP|SOCS|NID|AEC|__Secure-|__Host-|\*?GAPS)/;

// Cookies that live on .google.com; everything else is written to
// .youtube.com, which is the domain yt-dlp reads.
const GOOGLE_DOMAIN_COOKIES = /^(SID|HSID|SSID|APISID|SAPISID|__Secure-|LOGIN_INFO|\*?GAPS)/;

const NETSCAPE_HEADER =
  "# Netscape HTTP Cookie File\n" +
  "# Generated by Astral Cloud (.play cookie). Do not edit by hand.\n\n";

function envValue(name) {
  const value = process.env[name];
  return value && value.trim() ? value.trim() : undefined;
}

/** Looks like base64 of text rather than text itself? */
function looksBase64(value) {
  const text = String(value || "").trim();
  if (text.length < 24) return false;
  if (/\s/.test(text)) return false;
  if (!/^[A-Za-z0-9+/=]+$/.test(text)) return false;
  // Netscape cookie files and headers both contain '=' or ';' or tabs, which
  // are not in the base64 alphabet — so no ambiguity in practice.
  return true;
}

function tryBase64Decode(value) {
  // Chat clients happily wrap a long paste over several lines, so whitespace
  // is stripped before deciding whether this is base64 at all.
  const text = String(value || "").replace(/\s+/g, "");
  if (!looksBase64(text)) return null;
  try {
    const decoded = Buffer.from(text, "base64").toString("utf8");
    // Only accept the decode when it actually looks like cookies.
    if (!/SID=|\.youtube\.com|\tH?SID\t/i.test(decoded)) return null;
    return decoded;
  } catch {
    return null;
  }
}

/** A Cookie header ("a=b; c=d") -> [{name, value}]. */
function parseCookieHeader(text) {
  const out = [];
  for (const part of String(text || "").split(";")) {
    const trimmed = part.trim();
    if (!trimmed) continue;
    const index = trimmed.indexOf("=");
    if (index <= 0) continue;
    const name = trimmed.slice(0, index).trim();
    const value = trimmed.slice(index + 1).trim();
    if (!name) continue;
    out.push({ name, value });
  }
  return out;
}

function isCommentLine(line) {
  return line.startsWith("#") && !/^#HttpOnly_/i.test(line);
}

/** A cookies.txt -> [{name, value, domain, line}]. Ignores comments and blanks, keeps #HttpOnly_. */
function parseNetscape(text) {
  const out = [];
  for (const rawLine of String(text || "").split(/\r?\n/)) {
    const value = rawLine.trim();
    if (!value || isCommentLine(value)) continue;
    const fields = value.split("\t");
    if (fields.length < 7) continue;
    out.push({
      domain: fields[0],
      name: fields[5],
      value: fields[6],
      line: fields.slice(0, 7).join("\t"),
    });
  }
  return out;
}

/**
 * Normalise any accepted cookie text into {cookies, netscape, header}.
 * Returns null when the text has no cookies at all.
 */
function normalise(raw) {
  const decoded = tryBase64Decode(raw);
  const text = (decoded || String(raw || "")).trim();
  if (!text) return null;

  const isNetscape = /\t/.test(text) && /^\s*(#|\.?[a-z0-9.-]+\t)/im.test(text);
  const parsed = isNetscape ? parseNetscape(text) : parseCookieHeader(text);
  // Keep Google/YouTube cookies only. A header has no domains, so it is used
  // as given (the user chose what to send); a file export is filtered.
  const cookies = isNetscape
    ? parsed.filter((cookie) =>
        RELEVANT_DOMAIN.test(String(cookie.domain || "").replace(/^#HttpOnly_/i, ""))
      )
    : parsed;
  const rawUsable = cookies.filter((cookie) => cookie.name && cookie.value);
  if (!rawUsable.length) return null;
  if (!rawUsable.some((cookie) => KNOWN_COOKIE.test(cookie.name))) return null;

  // Deduplicate identical (domain, name) entries (browser exports often list
  // the same cookie twice across partitions; keep the later entry).
  const dedupMap = new Map();
  for (const cookie of rawUsable) {
    const cleanDom = String(cookie.domain || "").replace(/^#HttpOnly_/i, "").toLowerCase();
    dedupMap.set(`${cleanDom}\t${cookie.name}`, cookie);
  }
  const usable = [...dedupMap.values()];

  // Deduplicate header by cookie name, preferring .youtube.com over .google.com
  // when a browser export carries both.
  const headerMap = new Map();
  for (const cookie of usable) {
    const cleanDom = String(cookie.domain || "").replace(/^#HttpOnly_/i, "");
    const isYt = /(^|\.)youtube\.com$/i.test(cleanDom);
    if (!headerMap.has(cookie.name) || isYt) {
      headerMap.set(cookie.name, cookie.value);
    }
  }
  const header = [...headerMap.entries()].map(([name, val]) => `${name}=${val}`).join("; ");

  let netscape;
  if (isNetscape) {
    // Preserve each cookie's own Netscape line (including its exact domain and
    // #HttpOnly_ prefix) instead of looking up by name with .find(), which
    // previously overwrote .youtube.com cookies with .google.com ones.
    const lines = usable.map((cookie) => cookie.line).filter(Boolean);
    netscape = `${NETSCAPE_HEADER}${lines.join("\n")}\n`;
  } else {
    const expiry = Math.floor(Date.now() / 1000) + 365 * 24 * 60 * 60;
    const lines = usable.map(({ name, value }) => {
      const domain = GOOGLE_DOMAIN_COOKIES.test(name) ? ".google.com" : ".youtube.com";
      return [domain, "TRUE", "/", "TRUE", expiry, name, value].join("\t");
    });
    netscape = `${NETSCAPE_HEADER}${lines.join("\n")}\n`;
  }

  return { cookies: usable, header, netscape };
}

function stored() {
  const value = persist.get(STORE, null);
  if (!value || typeof value !== "object") return null;
  return value.text ? value : null;
}

/** Where the current cookies come from: "env" | "saved" | null. */
function source() {
  if (
    envValue("YT_COOKIES_B64") ||
    envValue("YT_COOKIES") ||
    envValue("YT_COOKIE") ||
    envValue("YT_COOKIES_FILE")
  ) {
    return "env";
  }
  return stored() ? "saved" : null;
}

function rawFromSource() {
  const b64 = envValue("YT_COOKIES_B64");
  if (b64) return b64;

  const netscape = envValue("YT_COOKIES");
  if (netscape) return netscape;

  const header = envValue("YT_COOKIE");
  if (header) return header;

  const file = envValue("YT_COOKIES_FILE");
  if (file) {
    try {
      return fs.readFileSync(file, "utf8");
    } catch {
      // fall through to a saved copy
    }
  }

  const cached = stored();
  return cached ? cached.text : null;
}

/**
 * The parsed session, or null when no usable cookies are configured.
 * Cheap enough to call per request (files are read once per process key).
 */
function cookies() {
  const raw = rawFromSource();
  if (!raw) return null;
  const parsed = normalise(raw);
  if (!parsed) return null;
  return parsed;
}

/** Cookie header for InnerTube, or null. */
function header() {
  const parsed = cookies();
  return parsed ? parsed.header : null;
}

let wroteFile = null; // {path, at}

/**
 * Write (once per version) a Netscape cookies.txt and return its path.
 * Returns null when no cookies are configured.
 */
function cookieFile() {
  const parsed = cookies();
  if (!parsed) return null;
  if (wroteFile && wroteFile.text === parsed.netscape && fs.existsSync(wroteFile.path)) {
    return wroteFile.path;
  }

  for (const target of [STATUS_FILE, FALLBACK_FILE]) {
    try {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, parsed.netscape, { mode: 0o600 });
      wroteFile = { path: target, text: parsed.netscape, at: Date.now() };
      return target;
    } catch (err) {
      console.warn(`[play] could not write the cookie file (${err.message})`);
    }
  }
  return null;
}

/** True when the loaded cookies actually belong to a signed-in session. */
function hasAuthCookies(parsed = cookies()) {
  if (!parsed) return false;
  return parsed.cookies.some((cookie) => AUTH_COOKIES.includes(cookie.name));
}

/** Save cookies from a chat message or a host env var. Throws on junk. */
function setCookies(raw, by = null) {
  const parsed = normalise(raw);
  if (!parsed) {
    throw new Error(
      "that doesn't look like youtube cookies. expected the contents of a " +
        "cookies.txt (or its base64)."
    );
  }
  persist.set(STORE, {
    text: String(raw).trim(),
    kind: hasAuthCookies(parsed) ? "signed-in" : "visitor",
    count: parsed.cookies.length,
    savedAt: Date.now(),
    by,
  });
  wroteFile = null;
  return {
    count: parsed.cookies.length,
    signedIn: hasAuthCookies(parsed),
    names: parsed.cookies.map((cookie) => cookie.name),
  };
}

function clearCookies() {
  const existed = Boolean(stored());
  persist.set(STORE, null);
  wroteFile = null;
  for (const target of [STATUS_FILE, FALLBACK_FILE]) {
    try {
      fs.rmSync(target, { force: true });
    } catch {
      // best effort
    }
  }
  return existed;
}

/**
 * Human-readable state for `.play cookie` with no argument. Never includes a
 * cookie value.
 */
function status() {
  const where = source();
  if (!where) {
    return {
      configured: false,
      text:
        "🍪 no youtube cookies set.\n\n" +
        "without them, YouTube answers \"Sign in to confirm you're not a bot\" " +
        "from this server's IP and every source dies.\n\n" +
        "to fix it:\n" +
        "1. in a browser, sign in to youtube.com\n" +
        "2. export cookies with the \"Get cookies.txt LOCALLY\" extension\n" +
        "3. base64 the file:  base64 -w0 cookies.txt\n" +
        "4. DM me:  .play cookie <that base64>",
    };
  }

  const parsed = cookies();
  if (!parsed) {
    return {
      configured: false,
      text: `🍪 cookies are set (${where}) but could not be parsed. send them again.`,
    };
  }

  const signedIn = hasAuthCookies(parsed);
  const savedAt = stored()?.savedAt;
  const age = savedAt ? Math.floor((Date.now() - savedAt) / 86400000) : null;

  return {
    configured: true,
    signedIn,
    source: where,
    text:
      `🍪 youtube cookies active (${where}): ${parsed.cookies.length} cookies` +
      `${signedIn ? ", signed-in session ✅" : " — no SID/HSID, so this is a visitor export ❌"}` +
      `${age !== null ? `\nsaved ${age === 0 ? "today" : `${age} day(s) ago`}` : ""}\n\n` +
      "`.play cookie clear` removes them. Expired cookies look identical to " +
      "valid ones, so re-export if `.play` starts blocking again.",
  };
}

module.exports = {
  cookies,
  header,
  cookieFile,
  setCookies,
  clearCookies,
  status,
  source,
  hasAuthCookies,
  normalise,
  parseCookieHeader,
  parseNetscape,
  AUTH_COOKIES,
  STATUS_FILE,
  _reset: () => {
    wroteFile = null;
  },
};
